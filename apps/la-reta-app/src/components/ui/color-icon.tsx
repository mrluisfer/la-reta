/**
 * Los iconos a todo color, aparte del set de línea.
 *
 * Rompen a propósito con el resto —un trazo y un solo acento— y solo donde se
 * elige un destino: la fila de accesos de Inicio y los dos botones de la hoja
 * del calendario. Son cosas que no se parecen en nada entre sí y, dibujadas
 * todas en el mismo verde, se leían como variantes de lo mismo: había que leer
 * la etiqueta para distinguirlas. Con su color propio se reconocen por la
 * forma, que es para lo que está un icono.
 *
 * Que el calendario de "Agregar al calendario" sea **el mismo** que el de la
 * ficha de Inicio no es ahorro de código: es lo que hace que las dos se lean
 * como el mismo sitio.
 *
 * El resto de la app se queda como estaba: en una lista de ajustes o en una
 * cabecera, un icono a color sería ruido.
 */

export type ColorIconName =
  | "calendar"
  | "pitch"
  | "jersey"
  | "bulb"
  | "pin"
  | "people"
  | "star"
  | "trophy"
  | "goal";

export function ColorIcon({
  name,
  size = 30,
}: {
  name: ColorIconName;
  size?: number;
}) {
  if (name === "calendar") return <CalendarMark size={size} />;
  if (name === "pitch") return <PitchMark size={size} />;
  if (name === "jersey") return <JerseyMark size={size} />;
  if (name === "pin") return <PinMark size={size} />;
  if (name === "people") return <PeopleMark size={size} />;
  if (name === "star") return <StarMark size={size} />;
  if (name === "trophy") return <TrophyMark size={size} />;
  if (name === "goal") return <GoalMark size={size} />;
  return <BulbMark size={size} />;
}

